_EXACT: Dict[str, Method] = {m.id: m for m in _METHODS if not m.id.endswith("*")}
_PATTERNS: List[Method] = sorted([m for m in _METHODS if m.id.endswith("*")], key=lambda m: -len(m.id))


def all_methods() -> List[Method]:
    return list(_METHODS)


def ids() -> List[str]:
    return sorted(m.id for m in _METHODS)


def resolve(method_id: str) -> Optional[Method]:
    """Tam kimlik, yoksa en uzun `önek*` deseni; kayıt yoksa None."""
    if not method_id:
        return None
    m = _EXACT.get(method_id)
    if m:
        return m
    for p in _PATTERNS:
        if method_id.startswith(p.id[:-1]):
            return p
    return None


def tool_method_id(tool_name: str) -> str:
    return f"tool:{tool_name}"


def resolve_tool(tool_name: str) -> Optional[Method]:
    """Sohbet tool'u için yöntem; kayıt yoksa None (genel/örtük varsayılan yoktur)."""
    return resolve(tool_method_id(tool_name))


def to_dict(m: Method) -> Dict[str, object]:
    d = asdict(m)
    d["class_label_tr"] = CLASS_INFO[m.cls]["label_tr"]
    d["class_label_en"] = CLASS_INFO[m.cls]["label_en"]
    return d


